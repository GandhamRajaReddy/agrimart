"""Train an explicitly demo-only candidate crop ranker from the AgriMart workbook.

The workbook labels are generated by a synthetic simulator. This script is for
pipeline prototyping and must not be used to publish agronomic recommendations.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_WORKBOOK = ROOT / "data" / "training" / "agrimart_synthetic_market_mandi_intelligence.xlsx"
MODEL_PATH = ROOT / "models" / "crop" / "crop_ranker.joblib"
METRICS_PATH = ROOT / "models" / "crop" / "crop_ranker_metrics.json"

TARGET = "recommended_crop_label"
GROUP_COLUMNS = ["state", "district", "year", "season"]
NUMERIC_FEATURES = [
    "year", "month", "latitude", "longitude", "rainfall_mm", "temperature_c",
    "humidity_pct", "soil_ph", "organic_carbon_pct", "nitrogen_kg_ha",
    "phosphorus_kg_ha", "potassium_kg_ha", "soil_moisture_pct",
    "crop_duration_days", "mandi_modal_price_inr_qtl",
    "price_volatility_30d_pct", "mandi_arrivals_qtl_day", "demand_index_0_1",
    "nearest_mandi_distance_km", "competitor_crop_area_ha",
]
CATEGORICAL_FEATURES = [
    "state", "district", "season", "crop", "climate_zone",
    "irrigation_type", "water_requirement",
]
FEATURES = NUMERIC_FEATURES + CATEGORICAL_FEATURES
FORBIDDEN_FEATURES = {
    "record_id", "recommended_crop_label", "best_crop_for_district_season",
    "recommendation_rank", "agronomic_market_score", "gross_revenue_inr_ha",
    "estimated_net_return_inr_ha", "net_margin_pct", "expected_yield_kg_ha",
    "estimated_cost_inr_ha",
}


def build_pipeline() -> Pipeline:
    numeric = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
    ])
    categorical = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("onehot", OneHotEncoder(handle_unknown="ignore")),
    ])
    preprocess = ColumnTransformer([
        ("numeric", numeric, NUMERIC_FEATURES),
        ("categorical", categorical, CATEGORICAL_FEATURES),
    ])
    classifier = RandomForestClassifier(
        n_estimators=500,
        min_samples_leaf=2,
        class_weight="balanced_subsample",
        max_features="sqrt",
        random_state=42,
        n_jobs=-1,
    )
    return Pipeline([("preprocess", preprocess), ("classifier", classifier)])


def group_ranking_metrics(frame: pd.DataFrame, probabilities: np.ndarray) -> dict:
    scored = frame[GROUP_COLUMNS + ["crop", TARGET]].copy()
    scored["score"] = probabilities
    top1_hits = []
    top3_hits = []
    group_count = 0
    for _, group in scored.groupby(GROUP_COLUMNS, dropna=False):
        positives = set(group.loc[group[TARGET] == 1, "crop"].astype(str))
        if not positives:
            continue
        ranked = group.sort_values(["score", "crop"], ascending=[False, True])
        selected = ranked["crop"].astype(str).tolist()
        top1_hits.append(bool(set(selected[:1]) & positives))
        top3_hits.append(bool(set(selected[:3]) & positives))
        group_count += 1
    return {
        "groups_evaluated": group_count,
        "group_top_1_hit_rate": float(np.mean(top1_hits)) if top1_hits else None,
        "group_top_3_hit_rate": float(np.mean(top3_hits)) if top3_hits else None,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workbook", type=Path, default=DEFAULT_WORKBOOK)
    parser.add_argument("--test-year", type=int, default=2025)
    parser.add_argument("--allow-non-karnataka", action="store_true",
                        help="Train on all six synthetic states instead of Karnataka only.")
    args = parser.parse_args()

    if not args.workbook.is_file():
        parser.error(
            f"Workbook not found: {args.workbook}. Place the supplied workbook at "
            "data/training/agrimart_synthetic_market_mandi_intelligence.xlsx "
            "or pass --workbook."
        )

    frame = pd.read_excel(args.workbook, sheet_name="Crop_Recommendation_Data")
    missing = sorted((set(FEATURES + GROUP_COLUMNS + [TARGET])) - set(frame.columns))
    if missing:
        raise ValueError(f"Workbook is missing required columns: {missing}")
    if set(FEATURES) & FORBIDDEN_FEATURES:
        raise AssertionError("Target leakage: forbidden feature included.")
    if not args.allow_non_karnataka:
        frame = frame.loc[frame["state"].astype(str).str.casefold() == "karnataka"].copy()
    frame = frame.dropna(subset=GROUP_COLUMNS + [TARGET, "crop"]).copy()
    frame[TARGET] = frame[TARGET].astype(int)
    if not set(frame[TARGET].unique()).issubset({0, 1}):
        raise ValueError("recommended_crop_label must contain only 0 and 1.")

    train = frame.loc[frame["year"] < args.test_year].copy()
    test = frame.loc[frame["year"] == args.test_year].copy()
    if train.empty or test.empty:
        raise ValueError("Temporal split is empty. Check test-year and workbook coverage.")
    train_groups = set(map(tuple, train[GROUP_COLUMNS].drop_duplicates().to_numpy()))
    test_groups = set(map(tuple, test[GROUP_COLUMNS].drop_duplicates().to_numpy()))
    if train_groups & test_groups:
        raise AssertionError("Group leakage detected across temporal split.")
    if train[TARGET].nunique() < 2 or test[TARGET].nunique() < 2:
        raise ValueError("Both temporal partitions must contain positive and negative labels.")

    model = build_pipeline()
    model.fit(train[FEATURES], train[TARGET])
    probabilities = model.predict_proba(test[FEATURES])[:, 1]
    predictions = (probabilities >= 0.5).astype(int)

    metrics = {
        "dataset": args.workbook.name,
        "dataset_source": "SYNTHETIC",
        "demo_only": True,
        "production_recommendations_enabled": False,
        "scope": "all_synthetic_states" if args.allow_non_karnataka else "Karnataka",
        "train_years": sorted(train["year"].unique().astype(int).tolist()),
        "test_year": args.test_year,
        "train_rows": int(len(train)),
        "test_rows": int(len(test)),
        "train_groups": int(train[GROUP_COLUMNS].drop_duplicates().shape[0]),
        "test_groups": int(test[GROUP_COLUMNS].drop_duplicates().shape[0]),
        "positive_rate_train": float(train[TARGET].mean()),
        "positive_rate_test": float(test[TARGET].mean()),
        "row_metrics": {
            "accuracy": float(accuracy_score(test[TARGET], predictions)),
            "balanced_accuracy": float(balanced_accuracy_score(test[TARGET], predictions)),
            "precision": float(precision_score(test[TARGET], predictions, zero_division=0)),
            "recall": float(recall_score(test[TARGET], predictions, zero_division=0)),
            "roc_auc": float(roc_auc_score(test[TARGET], probabilities)),
            "average_precision": float(average_precision_score(test[TARGET], probabilities)),
            "confusion_matrix": confusion_matrix(test[TARGET], predictions).tolist(),
            "classification_report": classification_report(
                test[TARGET], predictions, output_dict=True, zero_division=0
            ),
        },
        "group_metrics": group_ranking_metrics(test, probabilities),
        "feature_columns": FEATURES,
        "excluded_leakage_columns": sorted(FORBIDDEN_FEATURES),
        "warning": (
            "Metrics measure agreement with a synthetic simulator-generated label, "
            "not real-world agronomic accuracy, yield, or profitability."
        ),
    }

    MODEL_PATH.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump({"pipeline": model, "metadata": {
        "model_name": "agrimart-synthetic-crop-candidate-ranker",
        "model_version": "0.1.0",
        "dataset_source": "SYNTHETIC",
        "demo_only": True,
        "production_recommendations_enabled": False,
        "feature_columns": FEATURES,
        "trained_test_year": args.test_year,
        "scope": metrics["scope"],
    }}, MODEL_PATH)
    METRICS_PATH.write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    print(json.dumps({
        "model_path": str(MODEL_PATH),
        "metrics_path": str(METRICS_PATH),
        "row_metrics": metrics["row_metrics"],
        "group_metrics": metrics["group_metrics"],
        "warning": metrics["warning"],
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
